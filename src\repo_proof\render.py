from __future__ import annotations

from .models import AuditReport


STATUS = {"pass": "PASS", "warn": "WARN", "fail": "FAIL"}


def render_markdown(report: AuditReport, source: str = "manifest") -> str:
    lines = [
        "# Repository evidence audit",
        "",
        f"- Source: `{source}`",
        f"- Decision: **{report.decision.upper()}**",
        f"- Score: **{report.score}/{report.max_score}**",
    ]
    if report.critical_failures:
        lines.append(f"- Critical failures: `{', '.join(report.critical_failures)}`")
    lines += ["", "| Status | Check | Points | Evidence |", "|---|---|---:|---|"]
    for check in report.checks:
        evidence = check.evidence.replace("|", "\\|").replace("\n", " ")
        lines.append(
            f"| {STATUS[check.status]} | `{check.code}` {check.title} | "
            f"{check.points}/{check.max_points} | {evidence} |"
        )
    lines += ["", "Generated by [repo-proof](https://github.com/xiaosen017-maker/repo-proof).", ""]
    return "\n".join(lines)
